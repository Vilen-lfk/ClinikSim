def main(reset: bool = False) -> None:
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        if reset:
            db.execute(delete(Message))
            db.execute(delete(SimSession))
            db.execute(delete(Scenario))
            db.commit()
            print("БД очищена")
        existing = set(db.scalars(select(Scenario.title)).all())
        added = 0
        for data in SCENARIOS:
            if data["title"] in existing:
                continue
            db.add(Scenario(**data))
            added += 1
        db.commit()
        print(f"Добавлено сценариев: {added}")
    finally:
        db.close()

        if not db.scalar(select(User.id).where(User.username == "demo")):
            db.add(User(
                username="demo",
                password_hash=hash_password("demo1234"),
                full_name="Демо-студент",
                specialty="Терапия",
                course="2 год ординатуры",
            ))
            db.commit()
            print("Создан демо-пользователь: demo / demo1234")
        if not db.scalar(select(User.id).where(User.username == "teacher")):
            db.add(User(
                username="teacher",
                password_hash=hash_password("teacher1234"),
                full_name="Куратор ординатуры",
                role="teacher",
            ))
            db.commit()
            print("Создан куратор: teacher / teacher1234")
if __name__ == "__main__":
    main(reset="--reset" in sys.argv)